/**
 * Render src/features/commands/tree.generated.ts from the capabilities of
 * governance/module_registry.json: one group per capability that lists `ui.commands`,
 * and those commands. The registry stays the one place a command is written down;
 * this file is its view for the web, as docs/architecture/system-map.md is for people.
 *
 *   node scripts/command-tree.mjs           write the view
 *   node scripts/command-tree.mjs --check   fail when the committed view differs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const web = dirname(dirname(fileURLToPath(import.meta.url)));
export const REGISTRY = resolve(web, "../../../governance/module_registry.json");
export const TARGET = resolve(web, "src/features/commands/tree.generated.ts");
const CHANNELS = new Set(["front", "side", "background"]);

const text = (value, where) => {
  if (typeof value !== "string" || !value.trim()) throw new Error(`${where} needs a non-empty string`);
  return value;
};
const strings = (value, where) => {
  if (value === undefined) return [];
  if (!Array.isArray(value) || value.some((item) => typeof item !== "string")) throw new Error(`${where} must be a list of strings`);
  return value;
};

/** The tree, from the registry's parsed JSON. Throws on a command the palette could not show. */
export function commandTree(registry) {
  const groups = [], commands = [], seen = new Set();
  for (const capability of registry.capabilities ?? []) {
    const ui = capability.ui ?? {};
    if (!Array.isArray(ui.commands) || !ui.commands.length) continue;
    const id = text(capability.capability_id, "capability_id");
    groups.push({
      id, owner: text(capability.owner, `${id}.owner`), kind: text(capability.kind, `${id}.kind`), status: text(capability.status, `${id}.status`),
      purpose: { en: text(capability.purpose, `${id}.purpose`), "zh-CN": capability.purpose_zh ?? capability.purpose },
      terms: [...strings(capability.goals, `${id}.goals`), ...strings(capability.aliases, `${id}.aliases`)],
    });
    for (const [index, entry] of ui.commands.entries()) {
      const where = `${id}.ui.commands[${index}]`;
      const commandId = text(entry.id, `${where}.id`);
      if (seen.has(commandId)) throw new Error(`command ${commandId} is registered twice`);
      seen.add(commandId);
      const channel = entry.channel ?? ui.channel ?? "side";
      if (!CHANNELS.has(channel)) throw new Error(`${where}.channel must be front, side or background`);
      const surface = entry.surface ?? ui.surface ?? "hub";
      commands.push({
        id: commandId, group: id,
        label: { en: text(entry.label, `${where}.label`), "zh-CN": text(entry.label_zh, `${where}.label_zh`) },
        terms: strings(entry.aliases, `${where}.aliases`),
        surface,
        section: entry.section ?? ui.section ?? surface,
        channel,
        place: entry.place ?? null,
        shortcut: entry.shortcut ?? null,
        entries: strings(entry.entries, `${where}.entries`),
        args: strings(entry.args, `${where}.args`),
      });
    }
  }
  return { groups, commands };
}

export function render(registry) {
  const tree = commandTree(registry);
  return [
    "// Generated by apps/monkeyhub/web/scripts/command-tree.mjs from governance/module_registry.json.",
    "// Edit the capabilities there and run `npm run api:generate`; `npm run api:check` fails on drift.",
    'import type { CommandTree } from "./tree";',
    "",
    `export const COMMAND_TREE: CommandTree = ${JSON.stringify(tree, null, 2)};`,
    "",
  ].join("\n");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const rendered = render(JSON.parse(readFileSync(REGISTRY, "utf8")));
  if (process.argv.includes("--check")) {
    let committed = "";
    try { committed = readFileSync(TARGET, "utf8").replace(/\r\n/g, "\n"); } catch { /* missing counts as drift */ }
    if (committed !== rendered) {
      console.error(`Command tree drift: run \`npm run api:generate\` to rewrite ${TARGET}`);
      process.exit(1);
    }
    console.log("The command tree matches the module registry.");
  } else {
    writeFileSync(TARGET, rendered, "utf8");
    console.log(`Rendered ${TARGET}`);
  }
}
