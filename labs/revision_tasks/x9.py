# ---------------------------------------------------------------- what a task asks for

def evidence_value(record: StateRecord, family: str, topic: str) -> float | None:
    """The current reading of an evidence topic, from the record's own Reading@1 rows."""

    ids = x1.TOPICS[family][topic]["record"]
    rows = {e.entity_id: dict(e.fields) for e in record.entities_of("Reading@1")}
    current = [rows[i] for i in ids if i in rows and rows[i].get("status") == "current"]
    return float(current[-1]["value"]) if current else None


def requested_values(task: dict[str, Any], record: StateRecord) -> tuple[dict[str, float] | None, str]:
    """The typed values a task sets, or None with the reason there are none."""

    intent = task["intent"]
    if intent["kind"] == "set":
        return {k: float(v) for k, v in intent["set"].items()}, "typed values"
    if intent["kind"] == "from_evidence":
        value = evidence_value(record, task["family"], intent["topic"])
        if value is None:
            return None, f"no current evidence for {intent['topic']}"
        return {intent["parameter"]: intent["a"] * value + intent["b"]}, f"from the current evidence {intent['topic']} = {value}"
    if intent["kind"] == "missing":
        return None, f"the request needs {intent['parameter']} and gives no value: there is no number to write"
    target = intent["target"]
    note = (" A 3DM can carry a material on the object (an attribute edit), but the state has no parameter for it."
            if target.endswith(".material") else " No primitive field of the file holds it.")
    return None, f"attribute {target} = {intent['value']!r} has no parameter in the state.{note}"


def changed_values(values: dict[str, float], record: StateRecord) -> dict[str, float]:
    current = evaluate_parameters(record)
    return {k: v for k, v in values.items() if abs(float(current[k]) - v) > 1e-12}


def _apply(record: StateRecord, values: dict[str, float], base_record: str, base_state: str) -> tuple[StateRecord, list[dict[str, Any]]]:
    operators = []
    for key, value in values.items():
        operator = StateRecordOperator(kind=StateRecordEditKind.SET_SCALAR, base_record_digest=base_record, base_state_digest=base_state,
                                       target_ref=f"parameter:{key}", key=key, value=value)
        record = apply_state_record_operator(record, operator)
        operators.append(operator.to_dict())
        base_record, base_state = record.digest, record.state_digest
    return record, operators


# ---------------------------------------------------------------- DD-det

def classify(edits: list[dict[str, Any]], primitives: dict[str, native3dm.Primitive], start: dict[str, native3dm.Primitive]) -> tuple[str, str]:
    """full / partial / impossible / none, and why, from the edits the arm needed."""

    if not edits:
        return "none", "no object's numbers change"
    blocked = [e for e in edits if e["field"] == "unsupported"]
    if blocked:
        return "impossible", "; ".join(f"{e['object']}: {e['value']}" for e in blocked)
    meshes = sorted({e["object"] for e in edits if (primitives.get(e["object"]) or start.get(e["object"])).kind == "mesh"})
    counts: dict[str, int] = {}
    for e in edits:
        counts[e["field"]] = counts.get(e["field"], 0) + 1
    tally = ", ".join(f"{n} {k}" for k, n in sorted(counts.items()))
    if meshes:
        how = []
        for name in meshes:
            fields = {e["field"] for e in edits if e["object"] == name}
            how.append(f"{name} moved rigidly (one translation of its stored vertices)" if fields == {"translate"} else
                       f"{name} regenerated from the compiled loft by the harness's exact triangulation")
        return "partial", f"{tally}; held as a mesh (no native primitive): " + "; ".join(how)
    return "full", f"{tally}; every changed object is a native extrusion whose numbers were edited"


def dd_det(start_native: Path, values: dict[str, float], target: Path) -> dict[str, Any]:
    """The DD-det arm: change the start file's data so it holds the changed record; see the module docstring."""

    import rhino3dm  # noqa: F401  (imported before the clock starts, as REGEN's OCCT is initialised before its clock)

    t0 = time.perf_counter()
    read = native3dm.read_native(start_native)
    t1 = time.perf_counter()
    record, operators = _apply(fixtures.bound(read.record), values, read.binding["record_digest"], read.binding["state_digest"])
    t2 = time.perf_counter()
    program, objects_by_element, _ = pipeline.compile_record(record)
    new = native3dm.primitives(program)
    t3 = time.perf_counter()
    edits = native3dm.edits_between(read.primitives, new, native3dm.semantics_of(program))
    classification, reason = classify(edits, new, read.primitives)
    t4 = time.perf_counter()
    applied: list[dict[str, Any]] = []
    written = None
    if classification != "impossible":
        applied = native3dm.apply_edits(read.model, edits)
        native3dm.seal(read.model, record, program, parent_sha256=read.file_sha256)
        if not read.model.Write(str(target), 8):
            raise native3dm.NativeError(f"{target.name}: could not be written")
        written = target
    t5 = time.perf_counter()
    return {"classification": classification, "reason": reason, "record": record, "operators": operators, "edits": edits, "applied": applied,
            "path": written, "objects_by_element": objects_by_element, "start_primitives": read.primitives, "new_primitives": new,
            "ms": 1000.0 * (t5 - t0), "bytes": target.stat().st_size if written else 0,
            "phases_ms": {"read_and_check": 1000 * (t1 - t0), "patch": 1000 * (t2 - t1), "compile_and_convert": 1000 * (t3 - t2),
                          "diff": 1000 * (t4 - t3), "edit_seal_write": 1000 * (t5 - t4)}}


def edit_summary(edits: list[dict[str, Any]]) -> str:
    """``field:object`` pairs without the values (the values are in the task bundle)."""

    return ";".join(f"{e['field']}:{e['object']}" for e in edits)


# ---------------------------------------------------------------- REGEN

def regen(start: StateRecord, values: dict[str, float], workspace: Path) -> dict[str, Any]:
    """The production path: the changed record realized through OCCT, with the C-full state in the preview."""

    t0 = time.perf_counter()
    record, _ = _apply(start, values, start.digest, start.state_digest)
    provenance = {"state": canonical_json(carrier.payload(record, "C-full", None))}
    workspace.mkdir(parents=True)
    realization = pipeline.realize(record, workspace.resolve(), "regen", provenance=provenance)
    t1 = time.perf_counter()
    return {"realization": realization, "ms": 1000.0 * (t1 - t0),
            "bytes": realization.step_path.stat().st_size + realization.preview_path.stat().st_size, "phases_s": realization.phases_s}


# ---------------------------------------------------------------- one family's start

def family_start(family: str, root: Path) -> dict[str, Any]:
    """The fixture, its OCCT realization (the oracle's start and the exporter's reference) and its native file."""

    record = x1.FAMILY_FIXTURE[family]()
    bound = fixtures.bound(record)
    work = root / "families" / family
    (work / "start").mkdir(parents=True)
    realization = pipeline.realize(bound, (work / "start").resolve(), "start")
    t0 = time.perf_counter()
    export = native3dm.write_native(bound, work / "start.native.3dm")
    export_ms = 1000.0 * (time.perf_counter() - t0)
    bare = native3dm.write_native(bound, work / "start.native.nostate.3dm", state=None, compiled=(export.program, export.objects_by_element, {}))
    check = native3dm.compare_numbers(native3dm.geometry_boxes(export.path), native3dm.readback_numbers(realization))
    meshed = native3dm.compare_numbers(native3dm.mesh_model(export.path, work / "start.native.mesh.3dm"), native3dm.readback_numbers(realization))
    return {"record": record, "bound": bound, "realization": realization, "native": export.path,
            "exporter": {"objects": len(export.primitives), "native": export.native_ids, "mesh": export.mesh_ids,
                         "mesh_reasons": {k: export.primitives[k].reason for k in export.mesh_ids},
                         "boxes_match_readback": check["agree"], "max_box_dev_m": check["max_box_dev_m"],
                         "max_volume_rel_dev": check["max_volume_rel_dev"], "triangulation_matches_readback": meshed["agree"],
                         "native_bytes": export.bytes, "native_bytes_without_state": bare.bytes,
                         "preview_bytes": realization.preview_path.stat().st_size, "step_bytes": realization.step_path.stat().st_size,
                         "export_ms": export_ms}}


# ---------------------------------------------------------------- one task

def _median(values: list[float]) -> float | None:
    return statistics.median(values) if values else None


def oracle_spec(task_id: str, record: StateRecord) -> tuple[Path | None, str]:
    path = LAB / "tasks" / f"{task_id}-01.json"
    if not path.exists():
        return None, "no oracle task file"
    spec = taskspec.load(path)
    if taskspec.start_record(spec).digest != record.digest:
        return None, "the oracle task starts elsewhere"
    return path, "ok"


def run_task(task: dict[str, Any], start: dict[str, Any], out: Path, repeats: int) -> dict[str, Any]:
    task_dir = out / "tasks" / task["task_id"]
    task_dir.mkdir(parents=True)
    gold = task["gold"]["verdicts"]
    row: dict[str, Any] = {"task_id": task["task_id"], "family": task["family"], "type": task["type"], "intent": task["intent"]["kind"],
                           "gold_verdicts": "|".join(gold)}
    values, why = requested_values(task, start["record"])
    reasons_na = []
    if not any(v in JUDGED_VERDICTS for v in gold):
        reasons_na.append(f"gold is {'/'.join(gold)}: no geometry to edit")
    changed = changed_values(values, start["bound"]) if values is not None else None
    if values is None:
        reasons_na.append(why)
    elif not changed:
        reasons_na.append("the value equals the current one: nothing changes")
    row["values"] = json.dumps(changed if changed else values, sort_keys=True)
    bundle: dict[str, Any] = {"task": task, "values_source": why}
    if changed:
        (task_dir / "dd").mkdir()
        dd_runs, regen_runs = [], []
        for k in range(repeats):
            dd_runs.append(dd_det(start["native"], changed, task_dir / "dd" / f"candidate.r{k}.native.3dm"))
            regen_runs.append(regen(start["bound"], changed, task_dir / "regen" / f"r{k}"))
        dd, rg = dd_runs[0], regen_runs[0]
        geometry_moved = dd["classification"] != "none"
        if not geometry_moved:
            reasons_na.append("the change moves no geometry: " + dd["reason"])
        row.update({"would_class": dd["classification"], "would_reason": dd["reason"],
                    "objects_edited": len({e["object"] for e in dd["edits"]}), "edits": edit_summary(dd["edits"]),
                    "edit_modes": ";".join(f"{a['object']}={a['mode']}" for a in dd["applied"]),
                    "ms_dd": round(_median([r["ms"] for r in dd_runs]), 2), "ms_regen": round(_median([r["ms"] for r in regen_runs]), 2),
                    "bytes_dd": dd["bytes"], "bytes_regen": rg["bytes"]})
        row["speedup"] = round(row["ms_regen"] / row["ms_dd"], 1) if row["ms_dd"] else None
        owner = {**runner.element_of(start["realization"].objects_by_element), **runner.element_of(dd["objects_by_element"])}
        edited = sorted({e["object"] for e in dd["edits"]})
        row["edited_elements"] = "|".join(sorted({owner.get(o, "?") for o in edited}))
        row["edited_outside_gold_affected"] = "|".join(sorted({owner.get(o, "?") for o in edited} - set(task["gold"]["affected"])))
        bundle["dd"] = {"operators": dd["operators"], "edits": dd["edits"], "applied": dd["applied"], "phases_ms": dd["phases_ms"],
                        "ms_runs": [r["ms"] for r in dd_runs], "classification": dd["classification"], "reason": dd["reason"]}
        bundle["regen"] = {"ms_runs": [r["ms"] for r in regen_runs], "phases_s": rg["phases_s"]}
        if dd["path"] is not None:
            after = native3dm.read_native(dd["path"])
            really = sorted(n for n in set(after.primitives) | set(dd["start_primitives"])
                            if n not in after.primitives or n not in dd["start_primitives"]
                            or not native3dm.same_primitive(after.primitives[n], dd["start_primitives"][n]))
            row["unrelated_changed"] = len(set(really) - set(edited))
            row["edited_not_changed"] = len(set(edited) - set(really))
            row["state_reads_back"] = after.record.digest == dd["record"].digest
            dd_numbers = native3dm.mesh_model(dd["path"], task_dir / "dd" / "candidate.mesh.3dm")
            agreement = native3dm.compare_numbers(dd_numbers, native3dm.readback_numbers(rg["realization"]))
            row.update({"dd_agrees_regen": agreement["agree"], "max_box_dev_m": agreement["max_box_dev_m"],
                        "max_volume_rel_dev": agreement["max_volume_rel_dev"]})
            bundle["agreement"] = agreement
            spec_path, spec_why = oracle_spec(task["task_id"], start["record"])
            if spec_path is not None:
                report_dd = runner.run_oracle(spec_path, task_dir / "dd" / "candidate.mesh.3dm", start["realization"].preview_path,
                                              task_dir / "dd" / "oracle.json")
                report_rg = runner.run_oracle(spec_path, rg["realization"].preview_path, start["realization"].preview_path,
                                              task_dir / "regen" / "oracle.json")
                expected = taskspec.load(spec_path)["gold"]["expected_verdict"]
                row.update({"oracle_dd": report_dd["verdict"], "oracle_regen": report_rg["verdict"], "expected_verdict": expected,
                            "oracle_dd_violated": "|".join(r["id"] for r in report_dd.get("relations", []) if r["status"] == "violated")})
                bundle["oracle"] = {"dd": report_dd.get("relations"), "regen": report_rg.get("relations"), "error": report_dd.get("error")}
            else:
                row.update({"oracle_dd": f"unavailable ({spec_why})", "oracle_regen": f"unavailable ({spec_why})"})
    else:
        row["would_class"] = "none"
        row["would_reason"] = reasons_na[-1]
    if reasons_na:
        row["classification"], row["reason"] = "not_applicable", "; ".join(reasons_na)
    else:
        row["classification"], row["reason"] = row["would_class"], row["would_reason"]
    bundle["row"] = row
    (task_dir / "task.json").write_text(json.dumps(bundle, indent=1, sort_keys=True, default=str) + "\n", encoding="utf-8", newline="\n")
    return row


# ---------------------------------------------------------------- the run

COLUMNS = ["task_id", "family", "type", "intent", "gold_verdicts", "values", "classification", "reason", "would_class", "would_reason",
           "objects_edited", "edits", "edit_modes", "edited_elements", "edited_outside_gold_affected", "unrelated_changed", "edited_not_changed",
           "state_reads_back", "oracle_dd", "oracle_regen", "expected_verdict", "oracle_dd_violated", "dd_agrees_regen", "max_box_dev_m",
           "max_volume_rel_dev", "ms_dd", "ms_regen", "speedup", "bytes_dd", "bytes_regen", "error"]


def run(out: Path, *, families: tuple[str, ...] = FAMILIES, task_ids: tuple[str, ...] | None = None, repeats: int = 3) -> dict[str, Any]:
    tasks = [t for t in json.loads(x1.TASKS.read_text(encoding="utf-8"))["tasks"]
             if t["family"] in families and (task_ids is None or t["task_id"] in task_ids)]
    oracle_sha = taskspec.file_sha256(LAB / "oracle.py")
    identity = {"harness": runner.harness_identity(), "environment": runner.environment(), "oracle_sha256": oracle_sha, "repeats": repeats,
                "native_sha256": taskspec.file_sha256(LAB / "native3dm.py"), "x9_sha256": taskspec.file_sha256(Path(__file__))}
    (out / "identity.json").write_text(json.dumps(identity, indent=1, sort_keys=True) + "\n", encoding="utf-8", newline="\n")
    starts = {family: family_start(family, out) for family in sorted({t["family"] for t in tasks})}
    rows = []
    for task in tasks:
        try:
            row = run_task(task, starts[task["family"]], out, repeats)
        except (StateRecordError, pipeline.RealizationError, native3dm.NativeError, carrier.CarrierRefused) as exc:
            row = {"task_id": task["task_id"], "family": task["family"], "type": task["type"], "intent": task["intent"]["kind"],
                   "gold_verdicts": "|".join(task["gold"]["verdicts"]), "classification": "error", "reason": f"{type(exc).__name__}: {exc}"[:400],
                   "error": f"{type(exc).__name__}: {exc}"[:400]}
        rows.append(row)
        print(f"{row['task_id']:7} {row['classification']:14} would={row.get('would_class', ''):10} oracle_dd={row.get('oracle_dd', '-')!s:9} "
              f"agree={row.get('dd_agrees_regen', '-')!s:5} dd={row.get('ms_dd', '-')}ms regen={row.get('ms_regen', '-')}ms", flush=True)
    with (out / "x9.csv").open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=COLUMNS, extrasaction="ignore")
        writer.writeheader()
        writer.writerows(rows)
    executed = [r for r in rows if "ms_dd" in r and r.get("would_class") != "none"]
    applicable = [r for r in rows if r["classification"] in ("full", "partial", "impossible")]

    def oracle_stats(group: list[dict[str, Any]]) -> dict[str, Any]:
        judged = [r for r in group if r.get("oracle_dd") in ("held", "violated", "unchecked")]
        return {"judged": len(judged), "dd_equals_regen_verdict": sum(r["oracle_dd"] == r["oracle_regen"] for r in judged),
                "dd_equals_expected": sum(r["oracle_dd"] == r.get("expected_verdict") for r in judged),
                "verdicts_dd_regen_expected": {r["task_id"]: [r["oracle_dd"], r["oracle_regen"], r.get("expected_verdict")] for r in judged}}

    summary = {
        "tasks": len(rows),
        "by_class": {c: [r["task_id"] for r in rows if r["classification"] == c] for c in ("full", "partial", "impossible", "not_applicable")},
        "would_class_of_not_applicable": {r["task_id"]: r.get("would_class") for r in rows if r["classification"] == "not_applicable"},
        "errors": {r["task_id"]: r["error"] for r in rows if r.get("error")},
        "executed": len(executed),
        "dd_agrees_regen": sum(bool(r.get("dd_agrees_regen")) for r in executed),
        "unrelated_changed": sum(int(r.get("unrelated_changed") or 0) for r in executed),
        "oracle": {"applicable": oracle_stats(applicable),
                   "not_applicable_would": oracle_stats([r for r in executed if r["classification"] == "not_applicable"])},
        "ms": {"dd_median": _median([r["ms_dd"] for r in applicable]), "regen_median": _median([r["ms_regen"] for r in applicable]),
               "speedup_median": _median([r["speedup"] for r in applicable if r.get("speedup")]),
               "dd_max": max((r["ms_dd"] for r in applicable), default=None)},
        "bytes": {"dd_median": _median([r["bytes_dd"] for r in applicable]), "regen_median": _median([r["bytes_regen"] for r in applicable])},
        "exporter": {family: start["exporter"] for family, start in starts.items()},
        "not_native": {f"{family}/{name}": reason for family, start in starts.items() for name, reason in start["exporter"]["mesh_reasons"].items()},
    }
    (out / "x9_summary.json").write_text(json.dumps(summary, indent=1, sort_keys=True, default=str) + "\n", encoding="utf-8", newline="\n")
    return summary


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="X9: edit the 3DM's own data (DD-det) against the OCCT rebuild (REGEN).")
    parser.add_argument("--out", type=Path, required=True, help="a new or empty directory")
    parser.add_argument("--families", default=",".join(FAMILIES))
    parser.add_argument("--tasks", help="comma-separated task ids (default: every task of the families)")
    parser.add_argument("--repeats", type=int, default=3, help="timed runs of each arm per task; the first is judged")
    args = parser.parse_args(argv)
    out = args.out.resolve()
    if out.exists() and any(out.iterdir()):
        parser.error(f"{out} is not empty")
    out.mkdir(parents=True, exist_ok=True)
    summary = run(out, families=tuple(args.families.split(",")), task_ids=tuple(args.tasks.split(",")) if args.tasks else None,
                  repeats=max(1, args.repeats))
    print(json.dumps(summary, indent=1, sort_keys=True, default=str))
    return 0


if __name__ == "__main__":
    sys.exit(main())
