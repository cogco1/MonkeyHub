"""X9: make an architectural change by editing the numbers a 3DM file stores.

No Rhino, no host script or MCP, and no MonkeyHub producers-and-OCCT rebuild in
the editing arm. The start of every family is written once as a native editable
3DM (``native3dm.write_native``): extrusions whose profiles and paths are the
numbers, a mesh only where no primitive holds the solid (the dome), and the
C-full state in the document strings. Two deterministic arms then run each of
the 25 tasks of ``x1_tasks.json``:

| arm | what it does | what it runs |
|---|---|---|
| DD-det | read the start native file and check its state; apply the task's typed change to the record with ``apply_state_record_operator`` (base digests from the file's binding; derived parameters follow); compile the changed record (producers and the geometry compiler, pure Python, no OCCT) to learn each object's new primitive numbers; change only the objects whose numbers differ, in the opened file (``native3dm.apply_edits``); update the embedded state and binding; write | rhino3dm and the compiler |
| REGEN | apply the same change and ``pipeline.realize`` the changed record (producers, compiler, OCCT export and cold readback), with the C-full state in the preview's document strings as the hostless reviser writes it | the production path |

Interpretation: DD-det learns the new numbers from the compiled program. That is
the deterministic upper bound of editing the file's data: what a person or a model
would have to work out by hand, the compiler works out here, and the arm measures
whether the file's data can hold the result and what writing it costs.

DD-det classes each task:

- ``full``: every changed object is a native primitive, its numbers edited (a path set in place, or a new profile on a new extrusion of the same name and id, since openNURBS sets a profile only on an empty extrusion), or a native object added or deleted;
- ``partial``: a changed object is held as a mesh, so its new shape was moved as a mesh or regenerated by the harness's own exact triangulation of the compiled loft;
- ``impossible``: a changed object needs a boolean, loft or other solid the data cannot express (nothing is written);
- ``not_applicable``: the gold is only refuse, unknown or flag_rejected, the request has no value, or it changes no geometry. What the arm would do is still recorded.

The harness, not the oracle, turns the DD-det file into named meshes
(``native3dm.mesh_model``: exact triangulation of every stored extrusion, meshes
copied). The oracle judges it in its own ``python -I`` process
(``run.run_oracle``) with ``tasks/<task_id>-01.json`` when that file exists and
starts from the fixture, against the start's OCCT preview. Each object is also
compared with REGEN's cold-read STEP: box within 1e-6 m and volume within 1e-6
relative ("geometry digests agree"). Times are ``time.perf_counter`` around the
whole arm, the median of ``--repeats`` runs; bytes are what the arm writes (the
native file; REGEN's STEP and preview).

    python -m labs.revision_tasks.x9 --out <new empty dir>

``native3dm.apply_edits`` is the hook a model-driven arm (DD-agent) will write
its field-level edits through; no model is called here.
"""

